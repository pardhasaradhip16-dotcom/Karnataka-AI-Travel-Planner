/**
 * Get translated UI string by key with English fallback.
 */
export function t(key: string, lang: string = 'en'): string {
  const currentLang = (lang && typeof lang === 'string' && lang in UI_TRANSLATIONS ? lang : 'en') as AppLanguage;
  return UI_TRANSLATIONS[currentLang]?.[key] || UI_TRANSLATIONS['en']?.[key] || key;
}

/**
 * Get localized destination details for instant identification by tourists of any state.
 */
export function getLocalizedDestination(dest: { id: string; name: string; district: string; tagline: string; kannadaName: string }, lang: string = 'en'): {
  name: string;
  originalEnglishName: string;
  district: string;
  tagline: string;
  region: string;
  nativeScriptDisplay: string;
} {
  const normalizedId = dest.id === 'jogfalls' ? 'jog_falls' 
    : dest.id === 'belur_halebeedu' ? 'belur_halebidu'
    : dest.id === 'pattadakal_aihole' ? 'pattadakal'
    : dest.id;

  const destDict = DESTINATION_TRANSLATIONS[dest.id] || DESTINATION_TRANSLATIONS[normalizedId];
  const safeLang = (destDict && lang in destDict ? lang : 'en') as AppLanguage;
  const translation = destDict?.[safeLang];

  if (!translation) {
    return {
      name: lang === 'kn' ? dest.kannadaName : dest.name,
      originalEnglishName: dest.name,
      district: dest.district,
      tagline: dest.tagline,
      region: formatLocalizedRegion('', safeLang),
      nativeScriptDisplay: dest.kannadaName
    };
  }

  return {
    name: translation.name,
    originalEnglishName: dest.name,
    district: translation.district,
    tagline: translation.tagline,
    region: translation.region,
    nativeScriptDisplay: safeLang !== 'en' ? translation.name : dest.kannadaName
  };
}

